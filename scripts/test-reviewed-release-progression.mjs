import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { assertReviewedArtwork, assertReviewedCatalog, assertReviewedPublicationSource } from './reviewed-release-progression.mjs';
import { productFiles } from './testflight-cumulative-integrity.mjs';
const root = JSON.parse(fs.readFileSync('app.json')).expo.extra?.releaseTrack === 'testflight' ? process.cwd() : '/Users/dominic/powerlifting_app/powerlift_mobile_testflight';
const read = file => JSON.parse(fs.readFileSync(path.join(root, file)));
const state = read('config/testflight-release-integrity.json');
const policy = read('artwork-review/runtime-policy.json');
const catalog = read('config/governed-movement-art-taxonomy.json');
assertReviewedArtwork(root, state, policy);
assertReviewedCatalog(root, state, catalog);
const files = productFiles(root);
assertReviewedPublicationSource(root, state, files);
const missing = structuredClone(policy);
missing.approved_exact_artwork.splice(0, 1);
assert.throws(() => assertReviewedArtwork(root, state, missing), /disappeared|unapproved/);
const badCrop = structuredClone(policy);
badCrop.approved_exact_artwork.find(row => row.key === 'deficit_deadlift').logger_crop.zoom = 0.5;
assert.throws(() => assertReviewedArtwork(root, state, badCrop), /disappeared or changed/);
const replaced = structuredClone(policy);
replaced.approved_exact_artwork.find(row => row.key === 'barbell_overhead_press').app_sha256 = 'a'.repeat(64);
assert.throws(() => assertReviewedArtwork(root, state, replaced), /disappeared or changed/);
const reassigned = structuredClone(catalog);
reassigned.movements.find(row => row.id === 650).key = 'different_movement';
assert.throws(() => assertReviewedCatalog(root, state, reassigned), /catalog addition/);
const noCompatibility = { ...catalog, compatibility_movements: [] };
assert.throws(() => assertReviewedCatalog(root, state, noCompatibility), /identity disappeared/);
const changedHistory = structuredClone(catalog);
changedHistory.compatibility_movements[0].display_name = 'Rewritten historical evidence';
assert.throws(() => assertReviewedCatalog(root, state, changedHistory), /compatibility metadata/);
const required = Object.keys(state.reviewedPublication.requiredFiles)[0];
assert.throws(() => assertReviewedPublicationSource(root, state, { ...files, [required]: undefined }), /cumulative state disappeared/);
assert.throws(() => assertReviewedPublicationSource(root, state, { ...files, [required]: 'a'.repeat(64) }), /cumulative state disappeared/);
const noReceipt = structuredClone(state);
noReceipt.reviewedPublication.ownerEvidenceSha256 = 'a'.repeat(64);
assert.throws(() => assertReviewedPublicationSource(root, noReceipt, files), /owner evidence changed/);
console.log('Reviewed release progression PASS: original historical pins retained; exact human art/crop and cumulative patches verified; 9 unauthorized-loss/change/identity/receipt controls rejected.');
