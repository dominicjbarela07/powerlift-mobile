import assert from 'node:assert/strict';
import fs from 'node:fs';
import { model, fixture, plain, source } from './helpers/session-authoring-model.mjs';
const reorder = fs.readFileSync(new URL('../components/coach-mobile/InlineSessionReorder.tsx', import.meta.url), 'utf8');
const base = fixture();
const dirty = model.cloneSessionWorkspaceDraft(base);
dirty.title = 'Pull B'; dirty.movements[2].repsText = '15';
for (const id of [2, 3]) { dirty.movements[id].supersetGroup = 'A'; dirty.movements[id].supersetPosition = String(id - 1); }
const reordered = { ...dirty, accessoryOrder: [3, 2] };
const plan = plain(model.buildSessionWorkspaceSavePlan(reordered, base, 'lb'));
assert.equal(plan.metadataPatch.title, 'Pull B'); assert.deepEqual(plan.accessoryOrder, [3, 2]);
assert.equal(plan.movementUpdates.find((row) => row.item.id === 2).patch.reps_text, '15');
assert.equal(plan.movementUpdates.find((row) => row.item.id === 3).patch.superset_group, 'A');
assert.equal(model.sessionWorkspaceDraftIsDirty(reordered, base), true);
assert.deepEqual(plain(dirty.accessoryOrder), [2, 3], 'cancel leaves the original order and all local edits');
const linked = model.cloneSessionWorkspaceDraft(base); linked.items[4] = { id: 4, parent_item_id: 1, variant: 'BK' }; linked.coreOrder.push(4);
assert.deepEqual(plain(model.removeSessionDraftMovement(linked, 1).coreOrder), [], 'TOP removal includes linked work');
assert.match(source, /capabilities\.can_reorder && allItems\.length > 1/);
assert.match(source, /<InlineSessionReorder[\s\S]*onCancel=\{\(\) => setReordering\(false\)\}/);
assert.match(reorder, /parent_item_id[\s\S]*onApply\(draft\)/);
assert.match(reorder, /accessibilityActions[\s\S]*Move down[\s\S]*Move up/);
assert.doesNotMatch(reorder, /fetchJson|loadSession|onSaveSession/);
console.log('PASS: dirty reorder, grouped prescription preservation, cancel, linked work, accessible alternatives');
