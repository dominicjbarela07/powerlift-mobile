import assert from 'node:assert/strict';
import { model, fixture, plain, source, route } from './helpers/session-authoring-model.mjs';
const base = fixture();
assert.equal(model.sessionWorkspaceDraftIsDirty(base, base), false);
let draft = model.cloneSessionWorkspaceDraft(base);
draft.title = 'Changed'; draft.movements[1].reps = '8'; draft.movements[2].sets = '4'; draft.movements[2].repsText = '8-10';
let selected;
model.addSessionDraftMovement({ id: -1, lift: 'BN', variant: 'STRAIGHT', movement: 'Competition Bench', core_movement: { id: 102 }, designation: 'PRIMARY', sets: 4, reps: 6, rpe_target: 8 }, 'core', 'lb', (update) => { draft = update(draft); }, (id) => { selected = id; });
const firstId = selected;
model.addSessionDraftMovement({ id: -1, lift: 'VR', variant: 'STRAIGHT', movement: 'Pause Squat', core_movement: { id: 103 }, sets: 3, reps: 4 }, 'core', 'lb', (update) => { draft = update(draft); }, (id) => { selected = id; });
assert.notEqual(firstId, selected, 'new movement cannot replace a recovered local ID');
assert.equal(draft.movements[selected].targetLowLb, '', 'variants never receive an invented manual target');
const plan = plain(model.buildSessionWorkspaceSavePlan(draft, base, 'lb'));
assert.equal(plan.athleteId, 12); assert.equal(plan.metadataPatch.title, 'Changed');
assert.equal(plan.movementCreates[0].patch.lift, 'BN');
assert.equal(plan.movementCreates[0].patch.core_movement_id, 102);
assert.equal(plan.movementCreates[0].patch.designation, 'PRIMARY');
assert.equal(plan.movementUpdates[1].patch.movement_definition_id, 202);
assert.equal(plan.movementUpdates[1].patch.sets, '4');
assert.equal(plan.movementUpdates[1].patch.reps_text, '8-10');
assert.equal('target_low_lb' in plan.movementUpdates[1].patch, false);
assert.equal('target_high_lb' in plan.movementUpdates[1].patch, false);
const oldManualAccessory = model.createSessionWorkspaceDraft({ title: 'Legacy Accessory', athleteId: 12, scheduledDate: '2026-09-12', storageUnit: 'lb', notes: '', coreItems: [], accessoryItems: [{ id: 2, lift: 'ACC', variant: 'ACC', movement: 'Pulldown', movement_identity: { id: 202 }, sets: 3, reps_text: '10-12', rir_target: 2, coach_prescribed_low_kg: 30, coach_prescribed_high_kg: 35 }] });
assert.equal(oldManualAccessory.movements[2].targetLowLb, '', 'historical Accessory manual loads never enter the editable draft');
const editedOldManualAccessory = model.cloneSessionWorkspaceDraft(oldManualAccessory);
editedOldManualAccessory.movements[2].sets = '4';
const oldManualPatch = model.buildSessionWorkspaceSavePlan(editedOldManualAccessory, oldManualAccessory, 'lb').movementUpdates[0].patch;
assert.equal('target_low_lb' in oldManualPatch, false, 'editing an old Accessory does not resubmit a hidden manual target');
assert.equal('target_high_lb' in oldManualPatch, false, 'editing an old Accessory does not resubmit a hidden manual range');
assert.equal(model.sessionWorkspaceDraftIsDirty(draft, base), true);
assert.equal(model.sessionWorkspaceDraftIsDirty(model.cloneSessionWorkspaceDraft(base), base), false);
const changedDate = model.cloneSessionWorkspaceDraft(base);
changedDate.scheduledDate = '2026-10-03';
assert.equal(model.buildSessionWorkspaceSavePlan(changedDate, base, 'lb').metadataPatch.scheduledDate, '2026-10-03', 'date changes keep the established Session metadata persistence path');
const changedIdentity = model.cloneSessionWorkspaceDraft(base);
changedIdentity.items[2] = { ...changedIdentity.items[2], movement_identity: { id: 999 } };
assert.equal(model.sessionWorkspaceDraftIsDirty(changedIdentity, base), true, 'identity participates independently of labels');
assert.equal(model.buildSessionWorkspaceSavePlan(changedIdentity, base, 'lb').movementUpdates[0].patch.movement_definition_id, 999);
