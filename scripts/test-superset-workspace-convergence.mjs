import assert from 'node:assert/strict';
import fs from 'node:fs';
import { buildSupersetRoundModel } from '../lib/superset-rounds.ts';
import { supersetWorkspaceFocus, supersetMemberLabel } from '../lib/superset-workspace-focus.ts';
import { shouldOfferRestAfterAcceptedSet } from '../lib/set-rest-handoff.ts';
const member=(id,sets,indexes=[])=>({id,superset_pos:id,sets,set_logs:indexes.map(set_index=>({id:id*100+set_index,set_index}))});
const focus=(items,selection=null)=>supersetWorkspaceFocus(buildSupersetRoundModel(items),selection);
let items=[member(1,4),member(2,3)];
assert.equal(focus(items).next.itemId,1);
const selection={itemId:2,evidenceKey:focus(items).evidenceKey};
assert.equal(focus(structuredClone(items),selection).member.itemId,2,'refresh/unit changes preserve intentional inspection');
const accepted=(id,index)=>({created:true,set:{id:id*100+index,item_id:id,set_index:index}});
assert.equal(shouldOfferRestAfterAcceptedSet(accepted(1,1),[{group:'A',items}]),false);
items=[member(1,4,[1]),member(2,3)];
assert.equal(focus(items).next.itemId,2,'A saved → B current');
assert.equal(focus(items).roundIndex,1);
assert.equal(shouldOfferRestAfterAcceptedSet(accepted(2,1),[{group:'A',items}]),true,'rest only after both required members');
items=[member(1,4,[1]),member(2,3,[1])];
assert.equal(focus(items,selection).next.itemId,1,'new evidence invalidates old manual focus');
assert.equal(focus(items).roundIndex,2);
items=[member(1,4,[1,2,3]),member(2,3,[1,2,3])];
assert.equal(focus(items).roundIndex,4);
assert.deepEqual(buildSupersetRoundModel(items).rounds[3].entries.map(row=>row.itemId),[1],'unequal final round never invents B4');
const inspectingComplete={itemId:2,evidenceKey:focus(items).evidenceKey};
assert.equal(focus(items,inspectingComplete).member.itemId,2);
assert.equal(focus(items,inspectingComplete).next.itemId,1,'completed evidence inspection retains an explicit valid footer action');
assert.equal(shouldOfferRestAfterAcceptedSet(accepted(1,4),[{group:'A',items}]),true);
const tri=[member(1,1,[1]),member(2,1),member(3,1)];
assert.equal(focus(tri).next.itemId,2);
assert.equal(shouldOfferRestAfterAcceptedSet(accepted(2,1),[{group:'B',items:tri}]),false);
tri[1]=member(2,1,[1]);
assert.equal(focus(tri).next.itemId,3);
assert.equal(shouldOfferRestAfterAcceptedSet(accepted(3,1),[{group:'B',items:tri}]),true);
assert.equal(focus([member(1,4,[1,2,3,4]),member(2,3)]).next.itemId,2,'out-of-order training stays supported');
assert.equal(focus([member(1,1,[1]),member(2,1,[1])]).next,undefined);
assert.equal(shouldOfferRestAfterAcceptedSet({...accepted(3,1),replayed:true},[{group:'B',items:tri}]),false);
assert.equal(shouldOfferRestAfterAcceptedSet({...accepted(3,1),created:false},[{group:'B',items:tri}]),false);
assert.equal(supersetMemberLabel('B',3),'B3');
const route=fs.readFileSync('app/(tabs)/workout/[workoutId].tsx','utf8');
const view=fs.readFileSync('components/workout-logger/superset-round-workspace.tsx','utf8');
assert.doesNotMatch(view, /MOVEMENT PROGRESS|<MovementCardMaterial|Medallion|<SLButton|onLogRound|onLogMovement/);
assert.doesNotMatch(route,/Log superset round/);
assert.equal((route.match(/<SupersetRoundWorkspace/g)||[]).length,1,'one shared presentation for athlete and Coach Preview');
assert.match(route,/canLog=\{canLog && !isCoachView\}/);
assert.match(route,/phase=\{isPreSession \? 'pre' : isFinishedSession \? 'complete' : 'active'\}/);
assert.match(view,/showEvidence \? <CompactSetTimeline/,'saved evidence is available only on demand for the selected member');
assert.match(view,/only this round · rest after the set/, 'unequal final round copy never tells the athlete to alternate with a finished member');
assert.match(view,/<CanonicalMovementArtwork requireHumanApproval movement=\{item.movementArtwork\}/);
assert.match(route,/equipmentRequired: needsEquipmentSelection\(item\)/);
console.log('Superset storyboard: independent save focus, round rest, unequal and 3+ groups, resume, exact member actions and shared read-only preview PASS');
