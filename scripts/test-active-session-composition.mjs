import assert from 'node:assert/strict';
import fs from 'node:fs';
import { additionDraft, additionRequest, canEditActiveComposition, focusAfterCompositionChange, orderSessionMovementRows, validateCompositionResponse } from '../lib/active-session-composition.ts';
const selection = { id: 99, display_name: 'A renamed movement', kind: 'accessory' };
const composition = { item_ids: [11, 12, 13], items: [] };
const draft = additionDraft(selection, 'kg');
draft.repsText = '8-12'; draft.targetLowLb = '20'; draft.targetHighLb = '25';
const request = additionRequest(selection, draft, 'kg', composition, 12);
assert.equal(request.movement_definition_id, 99); assert.equal(request.before_item_id, 12);
assert.deepEqual(request.expected_item_ids, [11, 12, 13]); assert.equal(request.prescription.reps_text, '8-12');
assert.ok(Math.abs(Number(request.prescription.target_low_lb) * .45359237 - 20) < .003);
assert.equal(request.prescription.movement, undefined); assert.equal(request.prescription.is_substituted, undefined);
for (const tuple of [[false, true, 'in_progress', false], [true, false, 'in_progress', false], [true, true, 'completed', false], [true, true, 'in_progress', true], [undefined, true, 'in_progress', false]]) assert.equal(canEditActiveComposition(...tuple), false);
assert.equal(canEditActiveComposition(true, true, 'in_progress', false), true);
const coreSelection = { id: 1, display_name: 'Competition Squat', kind: 'core', lift: 'SQ' };
const coreDraft = additionDraft(coreSelection, 'lb'); coreDraft.scheme = 'TOP_BACKDOWN'; coreDraft.backdownSets = '2';
const core = additionRequest(coreSelection, coreDraft, 'lb', composition, null);
assert.equal(core.scheme, 'TOP_BACKDOWN'); assert.equal(core.prescription.backdown.sets, '2');
assert.equal(core.prescription.backdown.movement, undefined);
const prev = [{ id: 11, key: 'core:11' }, { id: 12, key: 'acc:12' }, { id: 13, key: 'acc:13' }];
const ordered = orderSessionMovementRows(prev, [12, 11, 13]);
assert.deepEqual(ordered.map(row => row.id), [12, 11, 13]); assert.deepEqual(prev.map(row => row.id), [11, 12, 13]);
assert.equal(focusAfterCompositionChange(prev, prev.filter(row => row.id !== 12), 'acc:12'), 'acc:13');
assert.equal(focusAfterCompositionChange(prev, prev.slice(0, 2), 'acc:13'), 'acc:12');
assert.equal(focusAfterCompositionChange(prev, ordered, 'core:11'), 'core:11');
assert.equal(focusAfterCompositionChange(prev, [], 'core:11'), null);
assert.equal(focusAfterCompositionChange([], prev, null), 'core:11');
const item = (id, logs = []) => ({ id, movement_definition_id: id + 40, set_logs: logs });
const payload = rows => ({ workout: { id: 7, core_items: rows, accessory_groups: [] } });
const old = payload([item(11), item(12, [{ id: 100 }])]);
const removed = { ...payload([item(12, [{ id: 100 }])]), composition_mutation: { removed_item_id: 11 } };
assert.equal(validateCompositionResponse(removed, old, '7'), true);
assert.equal(validateCompositionResponse({ ...payload([]), composition_mutation: { removed_item_id: 11 } }, payload([item(11)]), '7'), true);
assert.equal(validateCompositionResponse(payload([]), payload([item(11)]), '7'), false);
assert.equal(validateCompositionResponse({ ...removed, workout: { ...removed.workout, id: 8 } }, old, '7'), false);
assert.equal(validateCompositionResponse({ ...payload([item(12)]), composition_mutation: { removed_item_id: 11 } }, old, '7'), false);
assert.equal(validateCompositionResponse({ ...payload([item(11)]), composition_mutation: { removed_item_id: 12 } }, old, '7'), false);
assert.equal(validateCompositionResponse(payload([item(11), { ...item(12, [{ id: 100 }]), movement_definition_id: 999 }]), old, '7'), false);
const logger = fs.readFileSync('app/(tabs)/workout/[workoutId].tsx', 'utf8');
const editor = fs.readFileSync('components/workout-logger/active-composition-editor.tsx', 'utf8');
assert.match(logger, /<SessionActionsSheet/);
assert.match(logger, /onAdd=\{\(\) => openComposition\('add'\)\}/);
assert.match(logger, /onRemove=\{\(\) => openComposition\('remove'\)\}/);
assert.match(logger, /orderSessionMovementRows\(rows, workout.item_order\)/);
assert.match(editor, /GovernedAccessorySubstitutionPickerModal/); assert.match(editor, /MovementQuickPrescriptionEditor/);
const handler = logger.slice(logger.indexOf('{canEditComposition && compositionMode'), logger.indexOf('{canEditPrescription && prescriptionItemId'));
assert.match(handler, /workoutRequestManagerRef.current.cancel/);
assert.match(handler, /setAcceptedSetEvidenceItemIds/); assert.doesNotMatch(handler, /reset.*[Tt]imer|reset.*[Jj]ournal/);
console.log('PASS active Session composition: permissions, canonical requests, units, Core/Backdowns, insertion, focus, empty removal, evidence reconciliation and Logger wiring');
